-- Enable pgvector extension for future AI/RAG features
CREATE EXTENSION IF NOT EXISTS vector;

-- 1. Create custom ENUM types
CREATE TYPE user_role AS ENUM ('ADMIN', 'MANAGER', 'EMPLOYEE');
CREATE TYPE emp_status AS ENUM ('ACTIVE', 'ON_LEAVE', 'TERMINATED');
CREATE TYPE leave_status AS ENUM ('PENDING', 'APPROVED', 'REJECTED');
CREATE TYPE attendance_status AS ENUM ('PRESENT', 'LATE', 'HALF_DAY', 'ABSENT');

-- 2. Users Table (Authentication & RBAC)
CREATE TABLE users (
    id SERIAL PRIMARY KEY,
    email VARCHAR(255) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role user_role DEFAULT 'EMPLOYEE',
    is_active BOOLEAN DEFAULT TRUE,
    must_reset_password BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 3. Departments Table
CREATE TABLE departments (
    id SERIAL PRIMARY KEY,
    name VARCHAR(100) UNIQUE NOT NULL,
    description TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 4. Employees Table (Core Profile + AI Resume Skills Array)
CREATE TABLE employees (
    id SERIAL PRIMARY KEY,
    user_id INTEGER UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    phone VARCHAR(20),
    department_id INTEGER REFERENCES departments(id) ON DELETE SET NULL,
    designation VARCHAR(100) NOT NULL,
    salary NUMERIC(12, 2) NOT NULL CHECK (salary >= 0),
    skills TEXT[] DEFAULT '{}', -- Populated by AI Resume Parser on Day 5
    join_date DATE NOT NULL DEFAULT CURRENT_DATE,
    status emp_status DEFAULT 'ACTIVE',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- Add Manager Foreign Key to Departments after Employees table exists
ALTER TABLE departments 
ADD COLUMN manager_id INTEGER REFERENCES employees(id) ON DELETE SET NULL;

-- 5. Attendance Table (Unique constraint prevents double clock-in per day)
CREATE TABLE attendance (
    id SERIAL PRIMARY KEY,
    employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
    date DATE NOT NULL DEFAULT CURRENT_DATE,
    check_in TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    check_out TIMESTAMP WITH TIME ZONE,
    status attendance_status DEFAULT 'PRESENT',
    UNIQUE(employee_id, date)
);

-- 6. Leaves Table (Includes AI Co-pilot summary column)
CREATE TABLE leaves (
    id SERIAL PRIMARY KEY,
    employee_id INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
    leave_type VARCHAR(50) NOT NULL, -- 'SICK', 'CASUAL', 'EARNED'
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    reason TEXT NOT NULL,
    ai_impact_summary TEXT, -- Generated by AI Co-pilot on Day 6
    status leave_status DEFAULT 'PENDING',
    approved_by INTEGER REFERENCES employees(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CHECK (end_date >= start_date)
);

-- 7. Performance Indexes for Day 4 Search & Filtering
CREATE INDEX idx_employees_dept_status ON employees(department_id, status);
CREATE INDEX idx_employees_name ON employees(last_name, first_name);
CREATE INDEX idx_leaves_dates ON leaves(start_date, end_date, status);

